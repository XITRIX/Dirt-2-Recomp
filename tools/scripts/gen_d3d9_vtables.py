#!/usr/bin/env python3
"""Generates shims/d3d9/vtables.inc from DXVK's native d3d9.h.

Each D3D9 interface becomes a table of bridge functions in COM vtable order
(the mingw-style header re-declares inherited methods in every interface
block, so block order is vtable order). Slots 0-2 (IUnknown) use the bridge's
own QueryInterface/AddRef/Release; every other slot is SLOT(Interface, Method),
which selects a hand-written override when one exists.

Usage: gen_d3d9_vtables.py <d3d9.h> <out.inc>
"""
import re
import sys

INTERFACES = [
    "IDirect3D9", "IDirect3DDevice9", "IDirect3DStateBlock9", "IDirect3DSwapChain9",
    "IDirect3DResource9", "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9",
    "IDirect3DPixelShader9", "IDirect3DBaseTexture9", "IDirect3DTexture9",
    "IDirect3DVolumeTexture9", "IDirect3DCubeTexture9", "IDirect3DVertexBuffer9",
    "IDirect3DIndexBuffer9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DQuery9",
]


def main() -> None:
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    out = ["// Generated by tools/scripts/gen_d3d9_vtables.py from DXVK's d3d9.h. Do not edit.", ""]
    for name in INTERFACES:
        m = re.search(r"DECLARE_INTERFACE_\(\s*%s\s*,\s*\w+\s*\)\s*\{(.*?)\n\};" % name, src, re.S)
        if not m:
            raise SystemExit(f"interface {name} not found")
        methods = re.findall(r"STDMETHOD(?:_\([^,]+,\s*(\w+)\)|\((\w+)\))", m.group(1))
        names = [a or b for a, b in methods]
        assert names[:3] == ["QueryInterface", "AddRef", "Release"], name
        out.append(f"// {name}: {len(names)} methods")
        out.append(f"static const recomp_fn vt_{name}[] = {{")
        out.append(f"    &QI<{name}>, &AddRefB<{name}>, &ReleaseB<{name}>,")
        for n in names[3:]:
            out.append(f"    SLOT({name}, {n}),")
        out.append("};")
        out.append(f"template <> const VTableDesc& vtable_desc<{name}>() {{")
        out.append(f"    static const VTableDesc d{{\"{name}\", vt_{name}, {len(names)}}};")
        out.append("    return d;")
        out.append("}")
        out.append("")
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
