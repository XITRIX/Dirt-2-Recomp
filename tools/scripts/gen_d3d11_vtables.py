#!/usr/bin/env python3
"""Generates shims/d3d11/vtables.inc from the widl-style dxgi.h and d3d11.h that
DXMT builds against (include/native/directx).

For every interface (a `typedef struct <I>Vtbl { ... }` block, which lists all
methods, inherited ones included, in vtable order) it emits:
  - the bridge vtable: QI/AddRef/Release, then SLOT(I, Method) per method, so a
    hand-written OVERRIDE wins where one exists;
  - ARRAY_PARAM(I, Method, index, count_index) for interface-array parameters
    (`I *const *ppXs` in, or plural `I **ppXs` out, counted by a `Num...`
    parameter), which the bridge converts element by element;
  - LAYOUT_DIFFERS(T) for every struct whose 32-bit guest layout differs from
    the 64-bit host one (it holds a pointer, SIZE_T, HANDLE, HWND, ...), so the
    generic in-place pointer conversion refuses it at compile time: a method
    taking one needs a hand-written OVERRIDE;
  - WIDE_PARAM(I, Method) for methods with a 64-bit scalar parameter, which
    takes two guest stack slots (the generic bridge assumes one).

Usage: gen_d3d11_vtables.py <dxgi.h> <d3d11.h> <out.inc>
"""
import re
import sys

UNSAFE_SCALARS = {"SIZE_T", "HANDLE", "HWND", "HMONITOR", "HDC", "HMODULE", "LPCSTR", "LPSTR",
                  "LPCWSTR", "LPWSTR", "LPVOID", "LPCVOID", "ULONG_PTR", "LONG_PTR", "UINT_PTR",
                  "INT_PTR", "DWORD_PTR", "SSIZE_T", "PVOID"}
WIDE_SCALARS = {"UINT64", "INT64", "ULONGLONG", "LONGLONG", "LARGE_INTEGER", "ULARGE_INTEGER",
                "DOUBLE", "double"}


def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_param(p):
    p = re.sub(r"/\*.*?\*/", "", p).strip()
    m = re.match(r"(.*?)(\w+)\s*(\[\s*\w*\s*\])?$", p)
    typ, name = m.group(1).strip(), m.group(2)
    if m.group(3):
        typ += " *"
    return typ, name


def structs(src):
    """name -> list of field type strings (unions flattened)."""
    out = {}
    for m in re.finditer(r"typedef\s+(?:struct|union)\s+(\w+)\s*\{(.*?)\}\s*(\w+)\s*;", src, re.S):
        body = m.group(2)
        fields = [f.strip() for f in re.split(r";", body) if f.strip()]
        out[m.group(3)] = fields
        out[m.group(1)] = fields
    return out


def unsafe_structs(all_structs):
    unsafe = set()
    changed = True
    while changed:
        changed = False
        for name, fields in all_structs.items():
            if name in unsafe:
                continue
            for f in fields:
                toks = re.findall(r"\w+|\*", re.sub(r"(union|struct)\s*\{", "", f))
                if "*" in toks or any(t in UNSAFE_SCALARS for t in toks) or any(t in unsafe for t in toks):
                    unsafe.add(name)
                    changed = True
                    break
    return unsafe


def main():
    dxgi, d3d11, out_path = sys.argv[1:4]
    src = open(dxgi, errors="replace").read() + "\n" + open(d3d11, errors="replace").read()
    all_structs = structs(src)
    unsafe = unsafe_structs(all_structs)

    ifaces = []
    for m in re.finditer(r"typedef struct (\w+)Vtbl \{(.*?)\} \1Vtbl;", src, re.S):
        name, body = m.group(1), m.group(2)
        methods = []
        for mm in re.finditer(r"(\w[\w\s\*]*?)\s*\(STDMETHODCALLTYPE \*(\w+)\)\((.*?)\);", body, re.S):
            params = [parse_param(p) for p in split_params(mm.group(3))][1:]  # drop This
            methods.append((mm.group(2), params))
        ifaces.append((name, methods))
    names = {n for n, _ in ifaces} | {"IUnknown"}

    lines = ["// Generated by tools/scripts/gen_d3d11_vtables.py from DXMT's dxgi.h and d3d11.h. Do not edit.", ""]
    lines.append("// Structs whose guest (32-bit) layout differs from the host's: no in-place use.")
    for s in sorted(n for n in unsafe if not n.startswith("_") and not n.endswith("Vtbl") and n in all_structs):
        lines.append(f"LAYOUT_DIFFERS({s})")
    lines.append("")
    for name, methods in ifaces:
        assert [m for m, _ in methods[:3]] == ["QueryInterface", "AddRef", "Release"], name
        for mname, params in methods[3:]:
            counts = [i for i, (t, n) in enumerate(params) if n.startswith("Num")]
            for i, (t, n) in enumerate(params):
                base = re.match(r"(?:const\s+)?(\w+)\s*\*\s*(const\s*)?\*$", t)
                if not base or base.group(1) not in names:
                    continue
                plural = n.startswith("pp") and n.endswith("s")
                if (base.group(2) or plural) and counts:
                    cnt = min(counts, key=lambda c: abs(c - i))
                    lines.append(f"ARRAY_PARAM({name}, {mname}, {i}, {cnt})")
            if any(t.split()[-1] in WIDE_SCALARS for t, _ in params if "*" not in t):
                lines.append(f"WIDE_PARAM({name}, {mname})")
    lines.append("")
    for name, methods in ifaces:
        lines.append(f"// {name}: {len(methods)} methods")
        lines.append(f"static const recomp_fn vt_{name}[] = {{")
        lines.append(f"    &QI<{name}>, &AddRefB<{name}>, &ReleaseB<{name}>,")
        for mname, _ in methods[3:]:
            lines.append(f"    SLOT({name}, {mname}),")
        lines.append("};")
        lines.append(f"template <> const VTableDesc& vtable_desc<{name}>() {{")
        lines.append(f"    static const VTableDesc d{{\"{name}\", vt_{name}, {len(methods)}}};")
        lines.append("    return d;")
        lines.append("}")
        lines.append("")
    lines.append("#define BRIDGE_INTERFACES(X) \\")
    lines.append(" \\\n".join(f"    X({n})" for n, _ in ifaces))
    lines.append("")
    open(out_path, "w").write("\n".join(lines))
    print(f"{len(ifaces)} interfaces, {len(unsafe)} layout-differing structs")


if __name__ == "__main__":
    main()
