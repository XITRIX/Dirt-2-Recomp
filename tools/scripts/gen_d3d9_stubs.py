#!/usr/bin/env python3
"""Generates shims/d3d9/deko/stubs.inc from DXVK's native d3d9.h: one base class
per D3D9 interface for the Switch's D3D9-on-deko3d device (docs/SWITCH.md).

Stub<Interface> implements the whole interface: IUnknown with a reference count
and QueryInterface over the interface's own IID and its parents', and every
other method logs "not implemented" once (stub_result) and fails
(D3DERR_INVALIDCALL, or 0 for other return types). A device class derives from
the stub and overrides what the game uses, so the compiler checks every
override's signature and nothing else needs writing.

Usage: gen_d3d9_stubs.py <d3d9.h> <out.inc>
"""
import re
import sys

INTERFACES = [
    "IDirect3D9", "IDirect3DDevice9", "IDirect3DStateBlock9", "IDirect3DSwapChain9",
    "IDirect3DResource9", "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9",
    "IDirect3DPixelShader9", "IDirect3DBaseTexture9", "IDirect3DTexture9",
    "IDirect3DVolumeTexture9", "IDirect3DCubeTexture9", "IDirect3DVertexBuffer9",
    "IDirect3DIndexBuffer9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DQuery9",
]
METHOD = re.compile(r"STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\((\w+)\))\s*\(THIS_?\s*(.*?)\)\s*PURE;", re.S)


def main() -> None:
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    parents = {}
    out = ["// Generated by tools/scripts/gen_d3d9_stubs.py from DXVK's d3d9.h. Do not edit.", ""]
    for name in INTERFACES:
        m = re.search(r"DECLARE_INTERFACE_\(\s*%s\s*,\s*(\w+)\s*\)\s*\{(.*?)\n\};" % name, src, re.S)
        if not m:
            raise SystemExit(f"interface {name} not found")
        parents[name] = m.group(1)
        chain, p = [name], m.group(1)
        while p in parents:
            chain.append(p)
            p = parents[p]
        out.append(f"class Stub{name} : public {name} {{")
        out.append("public:")
        out.append(f"    virtual ~Stub{name}() = default;")
        out.append("    STDMETHOD(QueryInterface)(REFIID riid, void** out) override {")
        out.append("        if (!out) return E_POINTER;")
        iids = " || ".join(f"riid == __uuidof({i})" for i in chain + ["IUnknown"])
        out.append(f"        if ({iids}) {{")
        out.append("            *out = this;")
        out.append("            AddRef();")
        out.append("            return S_OK;")
        out.append("        }")
        out.append("        *out = nullptr;")
        out.append("        return E_NOINTERFACE;")
        out.append("    }")
        out.append("    STDMETHOD_(ULONG, AddRef)() override { return ++refs_; }")
        out.append("    STDMETHOD_(ULONG, Release)() override {")
        out.append("        const ULONG r = --refs_;")
        out.append("        if (r == 0) delete this;")
        out.append("        return r;")
        out.append("    }")
        for ret, n1, n2, args in METHOD.findall(m.group(2)):
            mname = n1 or n2
            if mname in ("QueryInterface", "AddRef", "Release"):
                continue
            ret = ret or "HRESULT"
            args = " ".join(args.split())
            body = (f"stub_result<{ret}>(\"{name}::{mname}\")" if ret != "void"
                    else f"stub_result<int>(\"{name}::{mname}\")")
            stmt = f"return {body};" if ret != "void" else f"{body};"
            out.append(f"    STDMETHOD_({ret}, {mname})({args}) override {{ {stmt} }}")
        out.append("")
        out.append("protected:")
        out.append("    std::atomic<ULONG> refs_{1};")
        out.append("};")
        out.append("")
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
