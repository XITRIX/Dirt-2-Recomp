#!/usr/bin/env python3
"""Assembles tests/lifter/cases.txt into cases.bin.txt.

The machine code is committed so the build needs no x86 assembler. Rerun this
after editing cases.txt; it needs a clang that can target i386 (Apple clang
can). Each case goes into its own section so local labels stay per case.
"""
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def parse_cases(path):
    cases = []
    for line in open(path):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        parts = [p.strip() for p in s.split("|")]
        cases.append((parts[0], parts[1]))
    return cases


def elf_sections(data):
    shoff = struct.unpack_from("<I", data, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)
    hdrs = [struct.unpack_from("<10I", data, shoff + i * shentsize) for i in range(shnum)]
    strtab = hdrs[shstrndx]
    out = {}
    for h in hdrs:
        name_off = strtab[4] + h[0]
        name = data[name_off:data.index(b"\0", name_off)].decode()
        out[name] = data[h[4]:h[4] + h[5]]
    return out


def main():
    cases = parse_cases(os.path.join(HERE, "cases.txt"))
    names = [n for n, _ in cases]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f"duplicate case names: {sorted(dup)}")
    src = [".intel_syntax noprefix"]
    for i, (_, text) in enumerate(cases):
        src.append(f'.section .text.c{i},"ax",@progbits')
        src.append(text)
    with tempfile.TemporaryDirectory() as tmp:
        s_path, o_path = os.path.join(tmp, "cases.s"), os.path.join(tmp, "cases.o")
        open(s_path, "w").write("\n".join(src) + "\n")
        subprocess.run(["clang", "-target", "i386-unknown-linux-gnu", "-c", s_path, "-o", o_path], check=True)
        secs = elf_sections(open(o_path, "rb").read())
    lines = ["# Generated by assemble.py from cases.txt. name | bytes | asm"]
    for i, (name, text) in enumerate(cases):
        if f".rel.text.c{i}" in secs:
            sys.exit(f"case {name} needs relocations (absolute or external reference)")
        lines.append(f"{name} | {secs[f'.text.c{i}'].hex().upper()} | {text}")
    open(os.path.join(HERE, "cases.bin.txt"), "w").write("\n".join(lines) + "\n")
    print(f"assembled {len(cases)} cases")


if __name__ == "__main__":
    main()
