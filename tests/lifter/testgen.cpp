// Lifts every case in cases.txt with the real FnLifter and writes one C file
// holding two variants per case (all flags live at ret, and default liveness)
// plus the LifterCase table the runner iterates.
//
//   lifter_testgen cases.txt cases.bin.txt out.c
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <map>
#include <sstream>

#include <algorithm>

#include "case_table.h"
#include "codegen/fn_lifter.h"

using namespace recomp;

namespace {

struct Case {
    std::string name, asm_text, options;
    std::vector<uint8_t> code;
    uint32_t addr = 0;
};

std::string trim(const std::string& s) {
    const size_t a = s.find_first_not_of(" \t\r");
    if (a == std::string::npos) return {};
    return s.substr(a, s.find_last_not_of(" \t\r") - a + 1);
}

std::vector<std::string> split_bar(const std::string& s) {
    std::vector<std::string> out;
    std::stringstream ss(s);
    for (std::string part; std::getline(ss, part, '|');) out.push_back(trim(part));
    return out;
}

std::string c_str(const std::string& s) {
    std::string o = "\"";
    for (char ch : s) {
        if (ch == '"' || ch == '\\') o += '\\';
        o += ch;
    }
    return o + "\"";
}

// Renames f_XXXXXXXX symbols so each variant gets its own copy.
std::string rename(const std::string& src, const std::string& prefix) {
    std::string o;
    o.reserve(src.size());
    for (size_t i = 0; i < src.size(); ++i) {
        if (src.compare(i, 2, "f_") == 0 && (i == 0 || !std::isalnum(static_cast<unsigned char>(src[i - 1]))) &&
            i + 10 <= src.size() && std::all_of(src.begin() + i + 2, src.begin() + i + 10, ::isxdigit)) {
            o += prefix;
            ++i;
            continue;
        }
        o += src[i];
    }
    return o;
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 4) {
        std::cerr << "usage: lifter_testgen cases.txt cases.bin.txt out.c\n";
        return 2;
    }
    std::map<std::string, std::pair<std::string, std::string>> bins;  // name -> (hex, asm)
    {
        std::ifstream in(argv[2]);
        for (std::string l; std::getline(in, l);) {
            if (trim(l).empty() || l[0] == '#') continue;
            auto p = split_bar(l);
            if (p.size() >= 3) bins[p[0]] = {p[1], p[2]};
        }
    }
    std::vector<Case> cases;
    {
        std::ifstream in(argv[1]);
        if (!in) {
            std::cerr << "cannot open " << argv[1] << "\n";
            return 1;
        }
        for (std::string l; std::getline(in, l);) {
            if (trim(l).empty() || trim(l)[0] == '#') continue;
            auto p = split_bar(l);
            if (p.size() < 2) {
                std::cerr << "bad case line: " << l << "\n";
                return 1;
            }
            Case c;
            c.name = p[0];
            c.asm_text = p[1];
            if (p.size() > 2) c.options = p[2];
            auto it = bins.find(c.name);
            if (it == bins.end() || it->second.second != c.asm_text) {
                std::cerr << "cases.bin.txt is stale for '" << c.name << "': run tests/lifter/assemble.py\n";
                return 1;
            }
            const std::string& hex = it->second.first;
            for (size_t i = 0; i + 1 < hex.size(); i += 2) c.code.push_back(uint8_t(std::stoul(hex.substr(i, 2), nullptr, 16)));
            if (c.code.size() + 1 > LT_CODE_STRIDE) {
                std::cerr << "case '" << c.name << "' is too long\n";
                return 1;
            }
            c.addr = LT_CODE_BASE + uint32_t(cases.size()) * LT_CODE_STRIDE;
            cases.push_back(std::move(c));
        }
    }

    // One synthetic image: each case followed by ret, padded with int3.
    std::vector<uint8_t> text(cases.size() * LT_CODE_STRIDE, 0xCC);
    for (const Case& c : cases) {
        std::copy(c.code.begin(), c.code.end(), text.begin() + (c.addr - LT_CODE_BASE));
        text[c.addr - LT_CODE_BASE + c.code.size()] = 0xC3;
    }
    const PeImage img = PeImage::from_code(LT_CODE_BASE - 0x1000, LT_CODE_BASE, text);
    const Disasm dis(img);
    DiscoveryConfig cfg;
    for (const Case& c : cases) cfg.extra_entries.push_back(c.addr);
    setenv("RECOMP_NO_GAPSCAN", "1", 1);
    Discovery disc(img, dis, cfg);
    disc.run();

    std::set<uint32_t> lifted;
    for (auto& [a, f] : disc.functions()) lifted.insert(a);
    for (const Case& c : cases)
        if (!lifted.count(c.addr)) {
            std::cerr << "case '" << c.name << "' was not discovered as a function\n";
            return 1;
        }

    std::string out = "/* Generated by lifter_testgen. Do not edit. */\n#include \"recomp/x86.h\"\n#include \"recomp/ops.h\"\n#include \"case_table.h\"\n\n";
    // Static prototypes give the definitions internal linkage.
    for (uint32_t a : lifted) out += std::format("static void live_{0:08X}(X86* c);\nstatic void dead_{0:08X}(X86* c);\n", a);
    out += "\n";
    LiftStats stats;
    for (auto& [a, f] : disc.functions()) {
        for (int live = 1; live >= 0; --live) {
            FnLifter fl(img, dis, disc, f, lifted, stats);
            fl.flags_live_out = live != 0;
            out += rename(fl.emit(), live ? "live_" : "dead_");
        }
    }

    // Flags undefined after the snippet, walking it linearly.
    auto undefined_flags = [&](const Case& c) {
        uint32_t undef = 0;
        for (uint32_t a = c.addr; a < c.addr + c.code.size();) {
            Insn in;
            if (!dis.decode(a, in)) break;
            if (const ZydisAccessedFlags* fl = in.ins.cpu_flags) {
                undef &= ~(fl->modified | fl->set_0 | fl->set_1);
                undef |= fl->undefined;
            }
            a = in.next();
        }
        return undef & F_ARITH;
    };

    for (const Case& c : cases) {
        out += std::format("static const uint8_t code_{:08X}[] = {{", c.addr);
        for (size_t i = 0; i < c.code.size(); ++i) out += std::format("0x{:02X}, ", c.code[i]);
        out += "0xC3};\n";
    }
    out += "\nconst LifterCase lifter_cases[] = {\n";
    for (const Case& c : cases)
        out += std::format("    {{{}, {}, {}, 0x{:08X}u, {}u, code_{:08X}, live_{:08X}, dead_{:08X}, 0x{:X}u}},\n",
                           c_str(c.name), c_str(c.asm_text), c_str(c.options), c.addr, c.code.size(), c.addr, c.addr,
                           c.addr, undefined_flags(c));
    out += "};\n";
    out += std::format("const uint32_t lifter_case_count = {}u;\n", cases.size());

    std::ofstream o(argv[3], std::ios::binary);
    o << out;
    if (!o) {
        std::cerr << "cannot write " << argv[3] << "\n";
        return 1;
    }
    if (stats.unimplemented) {
        std::cerr << "warning: " << stats.unimplemented << " unimplemented instruction sites in test cases\n";
        for (auto& [m, n] : stats.unimpl_by_mnemonic) std::cerr << "  " << m << " x" << n << "\n";
    }
    return 0;
}
